const connectionString = process.env.DATABASE_URL?.trim();
const postgres = Boolean(connectionString);
const deployed = process.env.NODE_ENV === 'production' || Boolean(process.env.RAILWAY_ENVIRONMENT_ID);

let pool;
let local;
if (postgres) {
  if (!/^postgres(ql)?:\/\//.test(connectionString)) throw new Error('DATABASE_URL은 PostgreSQL 연결 주소여야 합니다.');
  const databaseUrl = new URL(connectionString);
  const localTestDatabase = process.env.NODE_ENV === 'test' &&
    ['localhost', '127.0.0.1', '[::1]'].includes(databaseUrl.hostname);
  if (databaseUrl.searchParams.get('sslmode') === 'disable' && !localTestDatabase) {
    throw new Error('Supabase 연결에는 SSL이 필요합니다.');
  }
  if (!databaseUrl.searchParams.has('sslmode') && !localTestDatabase) {
    databaseUrl.searchParams.set('sslmode', 'require');
  }
  const { Pool } = require('pg');
  pool = new Pool({ connectionString: databaseUrl.toString(), max: 5 });
} else if (!deployed) {
  local = require('./db');
}

async function ensureReady() {
  if (!postgres) {
    if (!local) throw new Error('운영 환경에는 Supabase PostgreSQL DATABASE_URL이 필요합니다.');
    return;
  }
  await pool.query('CREATE SCHEMA IF NOT EXISTS tteonayo');
  await pool.query(`CREATE TABLE IF NOT EXISTS tteonayo.users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    name text NOT NULL,
    password_hash text NOT NULL,
    token_version integer NOT NULL DEFAULT 0,
    last_password_reset_at timestamptz
  )`);
  await pool.query('ALTER TABLE tteonayo.users ADD COLUMN IF NOT EXISTS token_version integer NOT NULL DEFAULT 0');
  await pool.query('ALTER TABLE tteonayo.users ADD COLUMN IF NOT EXISTS last_password_reset_at timestamptz');
  await pool.query(`CREATE TABLE IF NOT EXISTS tteonayo.travel_states (
    owner_id integer PRIMARY KEY REFERENCES tteonayo.users(id) ON DELETE CASCADE,
    version integer NOT NULL CHECK (version >= 1),
    data jsonb NOT NULL,
    import_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now()
  )`);
  await pool.query(`CREATE TABLE IF NOT EXISTS tteonayo.boards (
    id uuid PRIMARY KEY,
    owner_id integer NOT NULL REFERENCES tteonayo.users(id),
    title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 80),
    data jsonb NOT NULL,
    version integer NOT NULL DEFAULT 1 CHECK (version >= 1),
    legacy_board_id text,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
  )`);
  await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS boards_owner_legacy_id_key
    ON tteonayo.boards(owner_id, legacy_board_id) WHERE legacy_board_id IS NOT NULL`);
  await pool.query(`CREATE TABLE IF NOT EXISTS tteonayo.board_members (
    board_id uuid NOT NULL REFERENCES tteonayo.boards(id) ON DELETE CASCADE,
    user_id integer NOT NULL REFERENCES tteonayo.users(id) ON DELETE CASCADE,
    role text NOT NULL CHECK (role IN ('owner', 'editor', 'viewer')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (board_id, user_id)
  )`);
  await pool.query(`CREATE UNIQUE INDEX IF NOT EXISTS board_members_one_owner_key
    ON tteonayo.board_members(board_id) WHERE role = 'owner'`);
  await pool.query(`CREATE INDEX IF NOT EXISTS board_members_user_id_idx
    ON tteonayo.board_members(user_id)`);
}

function userFromRow(row) {
  return row && { id: row.id, email: row.email, name: row.name,
    passwordHash: row.password_hash, tokenVersion: row.token_version };
}

function stateFromRow(row) {
  return row && { ownerId: row.owner_id, version: row.version, data: row.data,
    importIds: row.import_ids, updatedAt: row.updated_at };
}

function canonical(value) {
  if (Array.isArray(value)) return value.map(canonical);
  if (value !== null && typeof value === 'object') {
    return Object.fromEntries(Object.keys(value).sort().map((key) => [key, canonical(value[key])]));
  }
  return value;
}

function sameData(left, right) {
  return JSON.stringify(canonical(left)) === JSON.stringify(canonical(right));
}

async function getUserById(id) {
  if (local) return local.get('users').find({ id }).value();
  const result = await pool.query('SELECT id, email, name, password_hash, token_version FROM tteonayo.users WHERE id = $1', [id]);
  return userFromRow(result.rows[0]);
}

async function getUserByEmail(email) {
  if (local) return local.get('users').find({ email }).value();
  const result = await pool.query('SELECT id, email, name, password_hash, token_version FROM tteonayo.users WHERE email = $1', [email]);
  return userFromRow(result.rows[0]);
}

async function getUsersByName(name) {
  if (local) return local.get('users').filter({ name }).value();
  const result = await pool.query('SELECT id, email, name, password_hash, token_version FROM tteonayo.users WHERE name = $1', [name]);
  return result.rows.map(userFromRow);
}

async function claimPasswordReset(id) {
  if (local) {
    const row = local.get('users').find({ id }).value();
    if (!row || (row.lastPasswordResetAt && Date.now() - Date.parse(row.lastPasswordResetAt) < 60_000)) return false;
    local.get('users').find({ id }).assign({ lastPasswordResetAt: new Date().toISOString() }).write();
    return true;
  }
  const result = await pool.query(`UPDATE tteonayo.users SET last_password_reset_at = now()
    WHERE id = $1 AND (last_password_reset_at IS NULL OR last_password_reset_at < now() - interval '60 seconds')
    RETURNING id`, [id]);
  return result.rowCount === 1;
}

async function createUser({ email, name, passwordHash }) {
  if (local) {
    if (local.get('users').find({ email }).value()) return null;
    const id = local.get('nextId').value();
    const user = { id, email, name, passwordHash, tokenVersion: 0 };
    local.get('users').push(user).write();
    local.set('nextId', id + 1).write();
    return user;
  }
  const result = await pool.query(`INSERT INTO tteonayo.users (email, name, password_hash)
    VALUES ($1, $2, $3) ON CONFLICT (email) DO NOTHING RETURNING id, email, name, password_hash, token_version`,
  [email, name, passwordHash]);
  return userFromRow(result.rows[0]) || null;
}

async function updateUserName(id, name) {
  if (local) {
    const row = await getUserById(id);
    if (!row) return null;
    local.get('users').find({ id }).assign({ name }).write();
    return { ...row, name };
  }
  const result = await pool.query(`UPDATE tteonayo.users SET name = $2 WHERE id = $1
    RETURNING id, email, name, password_hash, token_version`, [id, name]);
  return userFromRow(result.rows[0]) || null;
}

async function changeUserPassword(id, currentHash, nextHash) {
  if (local) {
    const row = await getUserById(id);
    if (!row || row.passwordHash !== currentHash) return null;
    const updated = { passwordHash: nextHash, tokenVersion: (row.tokenVersion ?? 0) + 1 };
    local.get('users').find({ id }).assign(updated).write();
    return { ...row, ...updated };
  }
  const result = await pool.query(`UPDATE tteonayo.users
    SET password_hash = $3, token_version = token_version + 1
    WHERE id = $1 AND password_hash = $2
    RETURNING id, email, name, password_hash, token_version`, [id, currentHash, nextHash]);
  return userFromRow(result.rows[0]) || null;
}

async function deleteUser(id, currentHash) {
  if (local) {
    const row = local.get('users').find({ id }).value();
    if (!row || row.passwordHash !== currentHash) return false;
    const ownedBoardIds = new Set(local.get('boards').filter({ ownerId: id }).map('id').value());
    local.set('boardMembers', local.get('boardMembers').value().filter((member) =>
      member.userId !== id && !ownedBoardIds.has(member.boardId)))
      .set('boards', local.get('boards').value().filter((board) => board.ownerId !== id))
      .set('travelStates', local.get('travelStates').value().filter((state) => state.ownerId !== id))
      .set('users', local.get('users').value().filter((user) => user.id !== id))
      .write();
    return true;
  }
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await client.query('SELECT password_hash FROM tteonayo.users WHERE id = $1 FOR UPDATE', [id]);
    if (!result.rows[0] || result.rows[0].password_hash !== currentHash) {
      await client.query('ROLLBACK');
      return false;
    }
    await client.query('DELETE FROM tteonayo.boards WHERE owner_id = $1', [id]);
    await client.query('DELETE FROM tteonayo.users WHERE id = $1', [id]);
    await client.query('COMMIT');
    return true;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function getTravelState(ownerId) {
  if (local) return local.get('travelStates').find({ ownerId }).value();
  const result = await pool.query('SELECT * FROM tteonayo.travel_states WHERE owner_id = $1', [ownerId]);
  return stateFromRow(result.rows[0]);
}

async function withOwnerLock(ownerId, callback) {
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(95041, $1)', [ownerId]);
    const result = await callback(client);
    await client.query('COMMIT');
    return result;
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function importTravelState(ownerId, importId, data) {
  if (local) {
    const row = await getTravelState(ownerId);
    if (row?.importIds?.includes(importId)) return { status: 'existing', row };
    if (row && !sameData(row.data, data)) return { status: 'conflict', row };
    if (row) {
      const next = { ...row, importIds: [...(row.importIds || []), importId] };
      local.get('travelStates').find({ ownerId }).assign(next).write();
      return { status: 'existing', row: next };
    }
    const created = { ownerId, version: 1, data, importIds: [importId], updatedAt: new Date().toISOString() };
    local.get('travelStates').push(created).write();
    return { status: 'created', row: created };
  }
  return withOwnerLock(ownerId, async (client) => {
    const current = await client.query('SELECT * FROM tteonayo.travel_states WHERE owner_id = $1 FOR UPDATE', [ownerId]);
    const row = stateFromRow(current.rows[0]);
    if (row?.importIds?.includes(importId)) return { status: 'existing', row };
    if (row && !sameData(row.data, data)) return { status: 'conflict', row };
    if (row) {
      const importIds = [...(row.importIds || []), importId];
      await client.query('UPDATE tteonayo.travel_states SET import_ids = $2::jsonb WHERE owner_id = $1',
        [ownerId, JSON.stringify(importIds)]);
      return { status: 'existing', row: { ...row, importIds } };
    }
    const created = { ownerId, version: 1, data, importIds: [importId], updatedAt: new Date().toISOString() };
    await client.query(`INSERT INTO tteonayo.travel_states (owner_id, version, data, import_ids)
      VALUES ($1, 1, $2::jsonb, $3::jsonb)`, [ownerId, JSON.stringify(data), JSON.stringify(created.importIds)]);
    return { status: 'created', row: created };
  });
}

async function saveTravelState(ownerId, version, data) {
  if (local) {
    const row = await getTravelState(ownerId);
    if ((row?.version ?? 0) !== version) return { status: 'conflict', row };
    if (!sameData(row?.data?.savedBoards ?? [], data.savedBoards ?? [])) return { status: 'legacy_conflict', row };
    const next = { ownerId, version: version + 1, data, importIds: row?.importIds ?? [], updatedAt: new Date().toISOString() };
    if (row) local.get('travelStates').find({ ownerId }).assign(next).write();
    else local.get('travelStates').push(next).write();
    return { status: 'saved', row: next };
  }
  return withOwnerLock(ownerId, async (client) => {
    const current = await client.query('SELECT * FROM tteonayo.travel_states WHERE owner_id = $1 FOR UPDATE', [ownerId]);
    const row = stateFromRow(current.rows[0]);
    if ((row?.version ?? 0) !== version) return { status: 'conflict', row };
    if (!sameData(row?.data?.savedBoards ?? [], data.savedBoards ?? [])) return { status: 'legacy_conflict', row };
    const next = { ownerId, version: version + 1, data, importIds: row?.importIds ?? [], updatedAt: new Date().toISOString() };
    if (row) await client.query(`UPDATE tteonayo.travel_states
      SET version = $2, data = $3::jsonb, updated_at = now() WHERE owner_id = $1`,
    [ownerId, next.version, JSON.stringify(data)]);
    else await client.query(`INSERT INTO tteonayo.travel_states (owner_id, version, data)
      VALUES ($1, 1, $2::jsonb)`, [ownerId, JSON.stringify(data)]);
    return { status: 'saved', row: next };
  });
}

function getLocalJwtSecret() {
  if (!local) return null;
  let secret = local.get('jwtSecret').value();
  if (!secret) {
    const { randomBytes } = require('node:crypto');
    secret = randomBytes(32).toString('hex');
    local.set('jwtSecret', secret).write();
  }
  return secret;
}

async function importLocalSnapshot(snapshot) {
  if (!postgres) throw new Error('로컬 데이터 이전에는 DATABASE_URL이 필요합니다.');
  const users = snapshot?.users;
  const states = snapshot?.travelStates;
  if (!Array.isArray(users) || !Array.isArray(states) ||
      users.some((user) => !Number.isInteger(user.id) || user.id < 1 ||
        typeof user.email !== 'string' || typeof user.name !== 'string' || typeof user.passwordHash !== 'string') ||
      states.some((state) => !Number.isInteger(state.ownerId) || !Number.isInteger(state.version) ||
        state.version < 1 || !state.data || typeof state.data !== 'object')) {
    throw new Error('로컬 DB 파일 형식이 올바르지 않습니다.');
  }
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('SELECT pg_advisory_xact_lock(95041, 0)');
    const existing = await client.query(`SELECT
      (SELECT count(*) FROM tteonayo.users) AS users,
      (SELECT count(*) FROM tteonayo.travel_states) AS states`);
    if (Number(existing.rows[0].users) || Number(existing.rows[0].states)) {
      throw new Error('대상 데이터베이스에 기존 데이터가 있어 이전을 중단했습니다.');
    }
    for (const user of users) {
      await client.query(`INSERT INTO tteonayo.users (id, email, name, password_hash)
        VALUES ($1, $2, $3, $4)`, [user.id, user.email, user.name, user.passwordHash]);
    }
    for (const state of states) {
      await client.query(`INSERT INTO tteonayo.travel_states
        (owner_id, version, data, import_ids, updated_at) VALUES ($1, $2, $3::jsonb, $4::jsonb, $5)`,
      [state.ownerId, state.version, JSON.stringify(state.data), JSON.stringify(state.importIds || []),
        state.updatedAt || new Date().toISOString()]);
    }
    await client.query(`SELECT setval(pg_get_serial_sequence('tteonayo.users', 'id'),
      GREATEST((SELECT COALESCE(max(id), 0) FROM tteonayo.users), 1),
      (SELECT count(*) > 0 FROM tteonayo.users))`);
    await client.query('COMMIT');
    return { users: users.length, states: states.length };
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

async function close() {
  if (pool) await pool.end();
}

